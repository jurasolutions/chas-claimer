/**
 * SC7.6, the synthetic-data guard. This repo is public, so every tracked file is scanned for
 * anything that could be a real person's or a real machine's details:
 *
 * - an NRIC/FIN outside the reserved `T9` block (GLOSSARY.md, "Synthetic identifier");
 * - a Singapore phone number outside the `+65 0000 nnnn` convention (GLOSSARY.md, "Synthetic phone number");
 * - an absolute home-directory path, or one flattened into a folder name, which gives away a local username;
 * - a session temp path, which gives away a user id and a session id;
 * - a private LAN address.
 *
 * The example strings in the self-tests below are assembled at run time, so this file scans clean
 * without exempting itself.
 */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

type Finding = { kind: string; match: string };

/** An NRIC/FIN shape in either case: prefix, seven digits, check letter. Masked forms (T••••000J) never match. */
const NRIC = /(?<![A-Za-z0-9])[STFGM]\d{7}[A-Z](?![A-Za-z0-9])/gi;
const SYNTHETIC_NRIC = /^T9/i;

/** A Singapore number with its country code, however it is spaced: +65 dddd dddd. */
const PHONE_WITH_CODE = /\+\s*65[\s-]*((?:\d[\s-]?){7}\d)(?!\d)/g;
/**
 * A local number as people write it: 8 digits starting 3, 6, 8 or 9, whole or split 4 + 4. A colon
 * or a hash in front does not hide it, so "Tel:" and "#" forms are caught too.
 */
const PHONE_LOCAL = /(?<![A-Za-z0-9_+\-/]|\d[.,])[3689]\d{3}[\s-]?\d{4}(?![A-Za-z0-9_\-/]|[.,]\d)/g;

const HOME_PATH = /(?:\/Users\/|\/home\/|[A-Za-z]:[\\/]+Users[\\/]+)[A-Za-z0-9._-]+/g;
/** Placeholders a doc may show in place of a real username. */
const HOME_PLACEHOLDER = /[\\/](?:Users|home)[\\/]+(?:<[^>]*>|name|username|you|me|user|USERNAME|Shared|Public)$/;
/**
 * A home directory flattened into a folder name, as tools spell a project's state folder: the path
 * with each separator turned into a dash. A placeholder such as `<name>` does not match.
 */
const HOME_SLUG = /(?<![A-Za-z0-9])-(?:Users|home)-[A-Za-z0-9._]+/g;
/**
 * A session's temp folder: anything under the macOS private temp root, or a Claude session folder
 * under the plain temp root. Both carry a user id and a session id.
 */
const TEMP_PATH = /\/private\/tmp\/[A-Za-z0-9._-]+|(?<!\/private)\/tmp\/claude-[A-Za-z0-9._-]*/g;
/** The bare session-folder prefix, with no id after it, names the shape and gives nothing away. */
const TEMP_PLACEHOLDER = /\/claude-$/;

const LAN_IP = /(?<![\d.])(?:192\.168|10\.\d{1,3}|172\.(?:1[6-9]|2\d|3[01]))\.\d{1,3}\.\d{1,3}(?![\d.])/g;

function scan(text: string): Finding[] {
  const found: Finding[] = [];
  for (const [m] of text.matchAll(NRIC)) if (!SYNTHETIC_NRIC.test(m)) found.push({ kind: "NRIC/FIN outside the T9 block", match: m });
  // A number with its country code is judged whole, then taken out so its last eight digits are not judged again.
  const withoutCode = text.replace(PHONE_WITH_CODE, (m, digits: string) => {
    if (!digits.replace(/\D/g, "").startsWith("0000")) found.push({ kind: "phone number outside +65 0000", match: m });
    return " ";
  });
  for (const [m] of withoutCode.matchAll(PHONE_LOCAL)) found.push({ kind: "phone number outside +65 0000", match: m });
  for (const [m] of text.matchAll(HOME_PATH)) if (!HOME_PLACEHOLDER.test(m)) found.push({ kind: "home-directory path", match: m });
  for (const [m] of text.matchAll(HOME_SLUG)) found.push({ kind: "home-directory path", match: m });
  for (const [m] of text.matchAll(TEMP_PATH)) if (!TEMP_PLACEHOLDER.test(m)) found.push({ kind: "session temp path", match: m });
  for (const [m] of text.matchAll(LAN_IP)) found.push({ kind: "private LAN address", match: m });
  return found;
}

/**
 * Files the guard does not read, each with its reason:
 * - `src/design-system/` is the vendored, read-only Jura design system (synced with `npm run sync:ds`).
 *   It holds no patient data and cannot be edited here, so a false positive in it could not be fixed.
 * - `package-lock.json` is generated by npm; its integrity hashes and version strings are not ours.
 */
const SKIPPED: readonly RegExp[] = [/^src\/design-system\//, /^package-lock\.json$/];

/**
 * Matches that are allowed, each tied to one file and one literal, with its reason. Keep this short:
 * the fix for a finding is almost always to move the value into the synthetic convention.
 */
const lan = (last: number) => ["10", "0", "0", String(last)].join(".");
const ALLOWED: readonly { file: string; match: string; reason: string }[] = [
  ...["server/channels/api.test.ts", "src/domain/settings.test.ts"].map((file) => ({
    file,
    match: lan(5),
    reason: "proves a payer address that is a private IP is refused; the test needs one to refuse",
  })),
  { file: "src/domain/hosts.test.ts", match: lan(1), reason: "proves a private IP is not taken for this machine" },
];

/** Binary files hold no text to scan. */
const BINARY = /\.(?:png|jpe?g|gif|webp|ico|woff2?|ttf|otf|eot|pdf|sqlite|db|zip|gz|mp4|webm)$/i;

function trackedFiles(): string[] {
  return execFileSync("git", ["ls-files", "-z"], { encoding: "utf8" })
    .split("\0")
    .filter((f) => f && !BINARY.test(f) && !SKIPPED.some((s) => s.test(f)));
}

describe("the synthetic-data guard's detectors", () => {
  const join = (...parts: string[]) => parts.join("");

  it("flags an NRIC/FIN outside the T9 block and passes one inside it", () => {
    expect(scan(`id ${join("S", "0000001", "Z")} here`)).toHaveLength(1);
    expect(scan(`id ${join("G", "1234567", "X")} here`)).toHaveLength(1);
    expect(scan(`id ${join("T", "9000018", "H")} here`)).toEqual([]);
    expect(scan(`masked ${join("T", "••••000J")}`)).toEqual([]);
  });

  it("flags a lowercase NRIC/FIN and passes a lowercase one inside the T9 block", () => {
    expect(scan(`id ${join("s", "1234567", "d")} here`)).toHaveLength(1);
    expect(scan(`id ${join("t", "9000018", "h")} here`)).toEqual([]);
  });

  it("flags a phone number glued to a colon or a hash", () => {
    expect(scan(join("Tel:", "9", "1234567"))).toHaveLength(1);
    expect(scan(join("Phone:", "9", "123 4567"))).toHaveLength(1);
    expect(scan(join("#", "9", "1234567"))).toHaveLength(1);
  });

  it("flags a Singapore phone number outside the convention and passes one inside it", () => {
    expect(scan(`call ${join("+65 ", "9", "000 0001")}`)).toHaveLength(1);
    expect(scan(`call ${join("+65", "8", "0000001")}`)).toHaveLength(1);
    expect(scan(`call ${join("9", "000 0001")} today`)).toHaveLength(1);
    expect(scan(`call ${join("6", "000-0001")} today`)).toHaveLength(1);
    expect(scan(`call ${join("+65 ", "0000 0018")}`)).toEqual([]);
    expect(scan("fee 900000 cents, 2026-11-14, seed 20_261_113, v1.2.3")).toEqual([]);
  });

  it("flags a home-directory path and passes a placeholder", () => {
    expect(scan(join("/", "Users", "/someone/projects"))).toHaveLength(1);
    expect(scan(join("/", "home", "/someone/x"))).toHaveLength(1);
    expect(scan(join("C:", "\\", "Users", "\\someone"))).toHaveLength(1);
    expect(scan(join("/", "Users", "/<name>/projects"))).toEqual([]);
  });

  it("flags a session temp path and a home directory spelled as a folder slug", () => {
    expect(scan(join("/", "private", "/tmp/", "claude-", "501/scratchpad"))).toHaveLength(1);
    expect(scan(join("/", "tmp/", "claude-", "501/x"))).toHaveLength(1);
    expect(scan(join("/", "private", "/tmp/", "build/out"))).toHaveLength(1);
    expect(scan(join("projects/", "-Users", "-someone-", "projects-repo/memory"))).toHaveLength(1);
    expect(scan(join("projects/", "-home", "-someone-", "repo"))).toHaveLength(1);
    // A sentence naming the shape, with no real folder in it, passes.
    expect(scan(join("a `/", "private", "/tmp/", "claude-` path and a `-Users", "-<name>-` slug"))).toEqual([]);
  });

  it("flags a private LAN address and passes a public one", () => {
    expect(scan(join("192.", "168.1.20"))).toHaveLength(1);
    expect(scan(join("10.", "0.0.12"))).toHaveLength(1);
    expect(scan("1.1.1.1 and version 10.4.2")).toEqual([]);
  });
});

describe("the synthetic-data guard (SC7.6)", () => {
  it("finds no real-looking identifier, phone number, home path or LAN address in any tracked file", () => {
    const files = trackedFiles();
    expect(files.length).toBeGreaterThan(100);

    const problems: string[] = [];
    for (const file of files) {
      let text: string;
      try {
        text = readFileSync(file, "utf8");
      } catch {
        continue; // tracked but deleted in the working tree
      }
      text.split("\n").forEach((line, i) => {
        for (const f of scan(line)) {
          if (ALLOWED.some((a) => a.file === file && a.match === f.match)) continue;
          problems.push(`${file}:${i + 1} ${f.kind}: ${f.match}`);
        }
      });
    }

    expect(problems).toEqual([]);
  });
});
